class Framebuffer:
    def __init__(self):
        self.buf = bytearray(BUFLEN)

    def clear(self):
        for i in range(BUFLEN):
            self.buf[i] = 0

    def pixel(self, x, y, on=True):
        if not (0 <= x < WIDTH and 0 <= y < HEIGHT):
            return
        idx = (y >> 3) * WIDTH + x
        bit = 1 << (y & 7)
        if on:
            self.buf[idx] |= bit
        else:
            self.buf[idx] &= ~bit & 0xFF

    def hline(self, x0, x1, y, on=True):
        for x in range(x0, x1):
            self.pixel(x, y, on)

    def rect_fill(self, x0, y0, w, h, on=True):
        for y in range(y0, y0 + h):
            for x in range(x0, x0 + w):
                self.pixel(x, y, on)

    def glyph(self, ch, x, y, on=True, scale=1):
        o = (ord(ch) - 32) * 5
        if o < 0 or o + 5 > len(_FONT):
            return
        for col in range(5):
            bits = ord(_FONT[o + col])
            for row in range(7):
                if not (bits & (1 << row)):
                    continue
                if scale == 1:
                    self.pixel(x + col, y + row, on)
                else:
                    self.rect_fill(x + col * scale, y + row * scale,
                                   scale, scale, on)

    def text(self, s, x, y, on=True, scale=1):
        adv = 6 * scale
        for ch in s:
            self.glyph(ch, x, y, on, scale)
            x += adv
        return x

    @staticmethod
    def text_width(s, scale=1):
        return max(0, len(s) * 6 * scale - scale)

    def text_centered(self, s, y, on=True, scale=1):
        x = (WIDTH - self.text_width(s, scale)) // 2
        return self.text(s, max(0, x), y, on, scale)

    def payload(self):
        return MAGIC + bytes(self.buf)
